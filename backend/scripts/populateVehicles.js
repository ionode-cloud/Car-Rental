export const ensureFullFleetInDatabase = async () => {
  try {
    for (const vData of NEW_FLEET_VEHICLES) {
      await Vehicle.findOneAndUpdate(
        { name: vData.name },
        vData,
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
    }
    const count = await Vehicle.countDocuments();
    console.log(`🚗 Fleet sync verified: ${count} total vehicles in database.`);
  } catch (err) {
    console.warn('⚠️ Fleet sync warning:', err.message);
  }
};

if (process.argv[1]?.endsWith('populateVehicles.js')) {
  connectDB().then(async () => {
    await ensureFullFleetInDatabase();
    process.exit(0);
  });
}
